"""Generate a forwarding proxy DLL (C source) for a system DLL.

The proxy goes in a game's folder. Every export jumps straight to the real system DLL,
and on load it also loads lsfghook.dll, which brings the native hook into the game.
Usage: gen_proxy.py NAME OUT.c
"""
